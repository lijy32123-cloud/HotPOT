"""Native-resolution learned contribution fields, fixed positive assembly."""
import hashlib
import math
import torch
from torch import nn
import torch.nn.functional as F
from common import BASE,resize,digest
from baseline_models import build as build_direct,state_hash
from program import assemble

ARM='hotpot_relaxed'


def core_hash(core):
    h=hashlib.sha256()
    for n,v in core.state_dict().items():
        if n.startswith('head.net.4.'):continue
        h.update(n.encode());h.update(v.detach().cpu().contiguous().numpy().tobytes())
    return h.hexdigest()


class RelaxedExpert(nn.Module):
    def __init__(self,core):
        super().__init__();self.core=core
        old=core.head.net[-1]
        core.head.net[-1]=nn.Conv2d(old.in_channels,80,1)
        nn.init.normal_(core.head.net[-1].weight,std=1e-4)
        nn.init.zeros_(core.head.net[-1].bias)
        # Seed0 direct filters initialize source readout; other core tensors
        # are exactly shared. No combustion fine-tuned weight is imported.
        with torch.no_grad():
            core.head.net[-1].weight[3::4].copy_(old.weight)
            core.head.net[-1].bias[3::4].copy_(old.bias)
        values=torch.load(BASE/'metadata/mean_std.pt',map_location='cpu',weights_only=True)
        normal=torch.tensor([float(v[0]) for v in values],dtype=torch.float64)
        self.register_buffer('normalization',normal)
        # Initial retention=1/2; initial generated contribution=mean(I)/2.
        # Fixed causal/data-normalization initialization, not fitted physics.
        self.source_bias=math.log(math.expm1(float(normal[1]/normal[3])*.5))
        self.diagnostics={}

    def intermediates(self,history):
        assert history.shape[1:]==(20,64,64,1)
        x=resize(history[...,0],(128,128)).permute(0,2,3,1).unsqueeze(-1).contiguous()
        raw=resize(self.core(x),(64,64)).reshape(len(history),20,4,64,64).double()
        mx,my,sx,sy=self.normalization.unbind()
        initial=(history[:,-1,...,0].double()*sx+mx).clamp_min(0)
        retention=torch.sigmoid(raw[:,:,2])
        generation=sy*F.softplus(raw[:,:,3]+self.source_bias)
        displacement=raw[:,:,:2]  # native pixel units; no arbitrary velocity cap
        return initial,retention,generation,displacement

    def forward(self,history):
        initial,retention,generation,displacement=self.intermediates(history)
        y,aux=assemble(initial,retention,generation,displacement)
        mx,my,sx,sy=self.normalization.unbind()
        with torch.no_grad():
            total=y.sum().clamp_min(1e-30)
            input_total=aux['initial_total'].sum().clamp_min(1e-30)
            self.diagnostics={'coefficient_resolution':64,'neural_calls_per_block':1,
                'retention_mean':float(retention.mean()),
                'displacement_rms_pixels':float(displacement.square().mean().sqrt()),
                'transported_output_fraction':float(aux['transported'].sum()/total),
                'generated_output_fraction':float(aux['born'].sum()/total),
                'lost_fraction_of_initial':float(aux['lost'].sum()/input_total),
                'escaped_fraction_of_initial':float(aux['escaped'].sum()/input_total),
                'balance_relative_max':float((aux['balance'].abs()/(aux['initial_total']+aux['born']+1e-30)).max())}
        return ((y-my)/sy).float().unsqueeze(-1)


def build(arm=ARM,seed=0):
    assert arm==ARM
    core,base=build_direct('hotpot_direct',seed)
    before=core_hash(core)
    model=RelaxedExpert(core)
    assert before==core_hash(core)
    ledger={**base,'arm':arm,'stored_parameters':sum(p.numel() for p in model.parameters()),
        'trainable_parameters':sum(p.numel() for p in model.parameters() if p.requires_grad),
        'initialization_sha256':state_hash(model),'direct_initialization_sha256':base['initialization_sha256'],
        'identical_direct_core_sha256':before,'normalization_sha256':digest(BASE/'metadata/mean_std.pt'),
        'adaptation':'same seed0 Direct core; 80-channel native-grid coefficient readout; only original six-PDE encoder reused',
        'target':'20 I frames generated by finite-interval positive contribution transport and birth',
        'intermediates':'per lead: two displacement fields, retained fraction, nonnegative generated contribution; all 64x64',
        'guarantees':'nonnegative output; conservative discrete transport; explicit loss, generation and escaped contribution ledger',
        'interpretation':'observed-intensity contribution closure, not identified species kinetics or true gas flow',
        'direct_prediction_special_case':True,'uses_diagnostic_fits':False,'uses_target_or_condition_inputs':False}
    return model,ledger
